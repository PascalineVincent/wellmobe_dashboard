// Active language — default to browser lang, fallback EN
let _lang = (() => {
  const stored = localStorage.getItem("mobins_lang");
  if (stored && I18N[stored]) return stored;
  const browser = (navigator.language || "en").slice(0,2).toLowerCase();
  return I18N[browser] ? browser : "en";
})();

function t(key) {
  return (I18N[_lang] && I18N[_lang][key]) || (I18N.en && I18N.en[key]) || key;
}

function setLang(lang) {
  if (!I18N[lang]) return;
  _lang = lang;
  localStorage.setItem("mobins_lang", lang);
  document.documentElement.lang = lang;
}

function getLang() { return _lang; }
